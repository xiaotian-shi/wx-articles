def load_keywords():
    if not KEYWORDS.exists():
        return [f'关键词{i:03d}' for i in range(1, 101)]
    return [x.strip() for x in KEYWORDS.read_text(encoding='utf-8').splitlines() if x.strip()][:100] or [f'关键词{i:03d}' for i in range(1, 101)]

def make_article(i, keyword):
    topic = TOPICS[(i-1) % len(TOPICS)]
    prefix = PREFIXES[(i-1) % len(PREFIXES)]
    template = TEMPLATES[(i-1) % len(TEMPLATES)]
    extra = f'\n\n本文围绕第 {i} 篇的整理主题展开，关键词占位为【关键词】；实际批量处理时可以使用关键词表中的第 {((i-1)%100)+1} 项进行替换。'
    body = template.format(topic=topic) + extra
    title = f'{prefix}：【关键词】_{topic}_{i:03d}.md'
    return title, body

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--replace-placeholder', action='store_true')
    args = ap.parse_args()
    keywords = load_keywords()
    for i in range(1, COUNT + 1):
        filename, body = make_article(i, keywords[(i-1) % len(keywords)])
        if args.replace_placeholder:
            filename = filename.replace('【关键词】', keywords[(i-1) % len(keywords)])
        (ROOT / filename).write_text(body + '\n', encoding='utf-8')
    print(f'generated {COUNT} articles')

if __name__ == '__main__':
    main()
